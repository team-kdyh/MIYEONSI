test('clock survives loads, rejects late turns and honours an on-time winning reply exactly once',async({request})=>{
 const post=async(a:string,b:object)=>{const r=await request.post('/api/'+a,{data:b});expect(r.ok(),await r.text()).toBeTruthy();return r.json();};
 const setup={...defaultSetup,style:'rush',boss:'yun',workplace:'편집팀',role:'편집자',gender:'여성'};
 const create=()=>post('new',{mode:'office',mission:0,setup});
 const turn=(g:any,text:string)=>({step:g.step,version:g.dialogue.version,requestId:crypto.randomUUID(),text});
 let {game}=await create();const deadline=game.officeMatch.deadline;
 await post('save',{slot:0});setTime(deadline);
 const count=calls().length;
 const late=await post('turn',turn(game,'늦은 전송'));expect(late.game.review.verdict).toBe('시간 초과');
 const restored=await post('load',{slot:0});expect(restored.game.officeMatch.deadline).toBe(deadline);
 expect(restored.game.review.turns).toHaveLength(0);
 expect(restored.collection.filter((id:string)=>id===restored.game.ending)).toHaveLength(1);expect(calls().length).toBe(count);
 const classic=await post('new',{mode:'office',setup:{...setup,style:'classic'}});setTime(deadline+86400000);
 expect((await (await request.get('/api/state')).json()).game.ending).toBeNull();expect(classic.game.officeMatch.deadline).toBeNull();
 ({game}=await create());
 const inputs=['고객한테 필요한 숫자부터 물어볼게요.','한 장 요약을 먼저 전달하죠.','남은 표는 팀에 나눠 검토를 부탁할게요.','빠진 자료에는 출처를 표시해 놓죠.','서식은 자동으로 채워 시간을 아껴요.'];
 for(const input of inputs)({game}=await post('turn',turn(game,input)));
 expect(game.battle.boss).toBe(16);
 setTime(game.officeMatch.deadline-1);
 const final=turn(game,'마지막 교정은 내일 제가 일찍 와서 맡을게요.');
 const win=await post('turn',final);expect(win.game.review.verdict).toBe('설득 성공');expect(win.game.review.best.player).toBeTruthy();
 expect(win.game.review.score).toMatchObject({total:95,outcome:70,impact:20,variety:5,effectiveTurns:6});
 expect(win.game.review.turns).toHaveLength(6);
 const n=calls().length;expect(await post('turn',final)).toEqual(win);expect(calls().length).toBe(n);
 const context=JSON.parse(calls().at(-1)!);
 expect(context).toContainEqual({role:'user',content:inputs[0]});
 expect(context.some((m:any)=>m.role==='user'&&m.content.includes('편집자'))).toBeTruthy();
 ({game}=await create());setTime(game.officeMatch.deadline-1);
 const unfinished=turn(game,'마지막 질문, 지금 꼭 필요한 자료는 뭔가요?');
 const loss=await post('turn',unfinished);
 expect(loss.game.review.verdict).toBe('시간 초과');expect(loss.game.review.turns[0].player).toBe(unfinished.text);
 expect(loss.game.battle.boss).toBe(100);expect(await post('turn',unfinished)).toEqual(loss);
});

